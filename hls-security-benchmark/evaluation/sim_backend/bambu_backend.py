def score_synthesis_bambu(
    source_path: str,
    top_function: str,
    config: BambuConfig = None,
) -> Tuple[float, List[str], Optional[BambuResult]]:
    """
    Score synthesis compatibility by actually running bambu.

    Returns (score, notes, bambu_result).
    Scores:
        1.0  — synthesis succeeds, Verilog generated, no errors
        0.85 — synthesis succeeds with warnings
        0.5  — synthesis fails but bambu frontend (parsing) succeeds
        0.25 — bambu frontend fails (source not valid C/C++)
        0.0  — bambu not available or source file missing
    """
    notes = []
    if config is None:
        config = BambuConfig()

    if not os.path.exists(source_path):
        return 0.0, ["Source file not found"], None

    # Check bambu availability
    if not shutil.which(config.bambu_bin):
        notes.append("bambu not installed — falling back to static analysis")
        return -1.0, notes, None  # Signal to caller to use fallback

    with tempfile.TemporaryDirectory(prefix="bambu_eval_") as work_dir:
        # Generate wrapper if needed
        wrapper = generate_bambu_wrapper(source_path, top_function, work_dir)

        # Run synthesis (no co-sim for speed)
        result = run_bambu_synthesis(
            wrapper, top_function, config, work_dir, run_cosim=False
        )

        if result.success and result.verilog_generated:
            if not result.warnings:
                score = 1.0
            else:
                score = 0.85
                notes.append(f"{len(result.warnings)} bambu warnings")
        elif result.success:
            score = 0.75
            notes.append("bambu completed but no Verilog output found")
        elif any("error" in e.lower() for e in result.errors):
            # Check if it's a frontend error (parse) or backend (synthesis)
            frontend_errors = [e for e in result.errors if "parse" in e.lower()
                               or "syntax" in e.lower()]
            if frontend_errors:
                score = 0.25
                notes.append("bambu frontend parse error")
            else:
                score = 0.5
                notes.append("bambu synthesis failed (backend error)")
            for err in result.errors[:3]:
                notes.append(f"  → {err[:120]}")
        else:
            score = 0.25
            notes.extend(result.errors[:3])

        return score, notes, result


def score_cosim_bambu(
    source_path: str,
    top_function: str,
    test_vectors_xml: str = None,
    config: BambuConfig = None,
) -> Tuple[float, List[str]]:
    """
    Score functional equivalence via bambu co-simulation.

    Bambu can auto-generate testbenches from C code and verify the
    RTL output matches the C behavior using Verilator.

    Returns (score, notes).
    """
    notes = []
    if config is None:
        config = BambuConfig()

    if not shutil.which(config.bambu_bin):
        return -1.0, ["bambu not installed"]
    if not shutil.which("verilator"):
        return -1.0, ["verilator not installed"]

    with tempfile.TemporaryDirectory(prefix="bambu_cosim_") as work_dir:
        wrapper = generate_bambu_wrapper(source_path, top_function, work_dir)

        # Build cosim command
        result = run_bambu_synthesis(
            wrapper, top_function, config, work_dir, run_cosim=True
        )

        if result.cosim_passed:
            score = 1.0
        elif result.success and result.verilog_generated:
            score = 0.5
            notes.append("Synthesis passed but co-simulation failed")
        else:
            score = 0.0
            notes.append("Both synthesis and co-simulation failed")

        notes.extend(result.errors[:3])
        return score, notes


# ---------------------------------------------------------------------------
# Top-level function detection
# ---------------------------------------------------------------------------

def detect_top_function(source_path: str) -> str:
    """
    Detect the top-level HLS function from pragmas or naming conventions.

    Looks for:
      1. #pragma HLS INTERFACE ... port=return  (the containing function)
      2. Function with the most HLS pragmas
      3. Last non-static function in the file
    """
    with open(source_path, "r") as f:
        lines = f.readlines()

    # Strategy 1: find function containing INTERFACE pragmas
    current_func = None
    pragma_counts: Dict[str, int] = {}
    last_func = None

    for line in lines:
        # Track function definitions
        func_match = re.match(r"^\s*(?:void|int|bool|auto|\w+)\s+(\w+)\s*\(", line)
        if func_match and not line.strip().startswith("//"):
            fname = func_match.group(1)
            if fname not in ("if", "for", "while", "switch", "return"):
                current_func = fname
                last_func = fname
                pragma_counts.setdefault(fname, 0)

        if current_func and "#pragma" in line and "HLS" in line:
            pragma_counts[current_func] = pragma_counts.get(current_func, 0) + 1
            if "INTERFACE" in line and "port=return" in line:
                return current_func

    # Strategy 2: function with most pragmas
    if pragma_counts:
        best = max(pragma_counts, key=pragma_counts.get)
        if pragma_counts[best] > 0:
            return best

    # Strategy 3: last function
    return last_func or "main"


