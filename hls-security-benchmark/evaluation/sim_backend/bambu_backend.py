@dataclass
class BambuResult:
    """Results from a bambu synthesis run."""
    success: bool = False
    verilog_generated: bool = False
    cosim_passed: bool = False
    latency_cycles: Optional[int] = None
    area_luts: Optional[int] = None
    area_ffs: Optional[int] = None
    area_dsps: Optional[int] = None
    area_brams: Optional[int] = None
    clock_mhz: Optional[float] = None
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    stdout: str = ""
    stderr: str = ""


def run_bambu_synthesis(
    source_path: str,
    top_function: str,
    config: BambuConfig,
    work_dir: str = None,
    run_cosim: bool = False,
) -> BambuResult:
    """
    Run PandA-bambu HLS synthesis on a C/C++ source file.

    Args:
        source_path: Path to the C/C++ source file
        top_function: Name of the top-level function to synthesize
        config: BambuConfig with tool settings
        work_dir: Working directory (created if None)
        run_cosim: Whether to also run co-simulation with Verilator

    Returns:
        BambuResult with synthesis outcomes
    """
    result = BambuResult()

    # Check bambu is available
    bambu_path = shutil.which(config.bambu_bin)
    if not bambu_path:
        result.errors.append(
            f"bambu not found at '{config.bambu_bin}'. "
            f"Install from https://github.com/ferrandi/PandA-bambu/releases"
        )
        return result

    # Check verilator for co-sim
    if run_cosim and not shutil.which("verilator"):
        result.warnings.append("verilator not found — skipping co-simulation")
        run_cosim = False

    # Create work directory
    if work_dir is None:
        work_dir = tempfile.mkdtemp(prefix="bambu_eval_")
    os.makedirs(work_dir, exist_ok=True)

    # Build command
    cmd = [
        bambu_path,
        os.path.abspath(source_path),
        f"--top-fname={top_function}",
        f"--clock-period={config.clock_period}",
        f"--device-name={config.device}",
        "--generate-interface=INFER",        # Understand HLS pragmas
        "-v2",                                # Verbosity level 2
        "--experimental-setup=BAMBU-BALANCED",
        "--compiler=I386_GCC8",              # Use bundled GCC-8 (both clangs segfault on Xilinx headers)
        "--std=c++14",                        # C++14 for ap_int compatibility
    ]

    # Add include paths for ap_int.h and hls_stream.h
    if os.path.isdir(_XILINX_HLS_INCLUDE):
        cmd.append(f"-I{_XILINX_HLS_INCLUDE}")
    if os.path.isdir(_LOCAL_STUBS):
        cmd.append(f"-I{_LOCAL_STUBS}")

    if run_cosim:
        cmd.extend([
            "--simulate",
            f"--simulator={config.simulator}",
        ])

    cmd.extend(config.extra_args)

    # Run bambu
    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=config.timeout,
            cwd=work_dir,
        )
        result.stdout = proc.stdout
        result.stderr = proc.stderr

        # Parse results
        result.success = (proc.returncode == 0)

        # Check for Verilog output
        hls_output = os.path.join(work_dir, "HLS_output")
        if os.path.isdir(hls_output):
            verilog_files = []
            for root, dirs, files in os.walk(hls_output):
                for f in files:
                    if f.endswith(".v") or f.endswith(".sv"):
                        verilog_files.append(os.path.join(root, f))
            result.verilog_generated = len(verilog_files) > 0

        # Parse timing/area from bambu output
        result.latency_cycles = _parse_latency(proc.stdout)
        result.clock_mhz = _parse_clock(proc.stdout)
        area = _parse_area(proc.stdout)
        if area:
            result.area_luts = area.get("luts")
            result.area_ffs = area.get("ffs")
            result.area_dsps = area.get("dsps")
            result.area_brams = area.get("brams")

        # Check co-simulation result
        if run_cosim:
            result.cosim_passed = "SIMULATION COMPLETED SUCCESSFULLY" in proc.stdout

        # Collect errors from both stdout and stderr
        # (bambu prints some errors to stdout)
        all_output = proc.stdout + "\n" + proc.stderr
        for line in all_output.split("\n"):
            line_stripped = line.strip()
            if not line_stripped:
                continue
            line_lower = line_stripped.lower()
            if "error:" in line_lower or "fatal:" in line_lower:
                result.errors.append(line_stripped)
            elif "warning:" in line_lower:
                result.warnings.append(line_stripped)

    except subprocess.TimeoutExpired:
        result.errors.append(f"bambu timed out after {config.timeout}s")
    except Exception as e:
        result.errors.append(f"bambu execution error: {str(e)}")

    return result


def _parse_latency(stdout: str) -> Optional[int]:
    """Extract latency in cycles from bambu output."""
    m = re.search(r"Total cycles\s*[:=]\s*(\d+)", stdout)
    if m:
        return int(m.group(1))
    # Alternative format
    m = re.search(r"Minimum execution time\s*[:=]\s*(\d+)", stdout)
    if m:
        return int(m.group(1))
    return None


def _parse_clock(stdout: str) -> Optional[float]:
    """Extract achieved clock frequency from bambu output."""
    m = re.search(r"Achieved clock frequency\s*[:=]\s*([\d.]+)", stdout)
    if m:
        return float(m.group(1))
    m = re.search(r"clock period\s*[:=]\s*([\d.]+)\s*ns", stdout, re.IGNORECASE)
    if m:
        period = float(m.group(1))
        return round(1000.0 / period, 2) if period > 0 else None
    return None


def _parse_area(stdout: str) -> Optional[Dict[str, int]]:
    """Extract area metrics from bambu output."""
    area = {}
    for key, patterns in [
        ("luts", [r"LUT\w*\s*[:=]\s*(\d+)", r"Slices?\s*[:=]\s*(\d+)"]),
        ("ffs",  [r"FF\w*\s*[:=]\s*(\d+)", r"Register\w*\s*[:=]\s*(\d+)"]),
        ("dsps", [r"DSP\w*\s*[:=]\s*(\d+)"]),
        ("brams",[r"BRAM\w*\s*[:=]\s*(\d+)", r"block\s*RAM\w*\s*[:=]\s*(\d+)"]),
    ]:
        for pattern in patterns:
            m = re.search(pattern, stdout, re.IGNORECASE)
            if m:
                area[key] = int(m.group(1))
                break
    return area if area else None


