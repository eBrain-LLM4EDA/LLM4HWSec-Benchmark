# Bambu has initial support for ap_uint/ap_int since PandA 2024.10, but
# the support is partial. For maximum compatibility, we provide a thin
# adaptation layer that maps our benchmark's ap_uint usage to bambu's
# supported subset. For types <= 64 bits we use native C types; for wider
# types we use bambu's built-in ac_int types if available.

BAMBU_AP_SHIM = r"""
// ---- Bambu compatibility shim for ap_uint/ap_int ----
// Maps ap_uint<W> to native C types for W <= 64, uses __uint128_t for
// W <= 128. For wider types, bambu's ac_int support is required.
// This shim is auto-generated by the benchmark evaluation framework.

#ifndef BAMBU_AP_SHIM_H
#define BAMBU_AP_SHIM_H

#include <stdint.h>

#ifdef __BAMBU__
// When compiled by bambu, use its native integer handling
template<int W> struct ap_uint_native;
template<> struct ap_uint_native<1>   { typedef uint8_t  type; };
template<> struct ap_uint_native<2>   { typedef uint8_t  type; };
template<> struct ap_uint_native<4>   { typedef uint8_t  type; };
template<> struct ap_uint_native<6>   { typedef uint8_t  type; };
template<> struct ap_uint_native<8>   { typedef uint8_t  type; };
template<> struct ap_uint_native<10>  { typedef uint16_t type; };
template<> struct ap_uint_native<16>  { typedef uint16_t type; };
template<> struct ap_uint_native<32>  { typedef uint32_t type; };
template<> struct ap_uint_native<64>  { typedef uint64_t type; };
template<> struct ap_uint_native<128> { typedef __uint128_t type; };
#endif

#endif // BAMBU_AP_SHIM_H
"""


def generate_bambu_wrapper(
    source_path: str,
    top_function: str,
    output_dir: str,
) -> str:
    """
    Generate a bambu-compatible wrapper for a benchmark HLS source file.
    Translates Vitis HLS pragmas to bambu-compatible format.
    """
    with open(source_path, "r") as f:
        source = f.read()

    # Bambu-supported interface modes (from PandA docs):
    #   ap_none, ap_ack, ap_vld, ap_ovld, ap_hs, ap_fifo, ap_memory
    # Bambu-supported pragmas: interface, unroll, inline, dataflow, cache
    # NOT supported: PIPELINE, BIND_STORAGE, LOOP_TRIPCOUNT, ARRAY_PARTITION

    # Vitis-to-bambu interface mode mapping
    IFACE_MAP = {
        "ap_ctrl_hs": "ap_hs",
        "ap_ctrl_none": "ap_none",
        "axis": "ap_fifo",
        "ap_none": "ap_none",
        "ap_vld": "ap_vld",
        "ap_hs": "ap_hs",
        "ap_fifo": "ap_fifo",
        "ap_memory": "ap_memory",
        "m_axi": "ap_memory",     # Approximate: m_axi → memory interface
        "s_axilite": "ap_none",   # Approximate: s_axilite → simple port
    }

    lines = source.split("\n")
    translated = []
    for line in lines:
        stripped = line.strip()
        indent = line[:len(line) - len(line.lstrip())]

        if not (stripped.startswith("#pragma") and "HLS" in stripped):
            translated.append(line)
            continue

        upper = stripped.upper()

        # Remove unsupported pragmas entirely
        if any(kw in upper for kw in ["BIND_STORAGE", "LOOP_TRIPCOUNT",
                                        "ARRAY_PARTITION", "ARRAY_RESHAPE",
                                        "STREAM", "LATENCY", "ALLOCATION"]):
            translated.append(f"{indent}// [bambu] {stripped}")
            continue

        # PIPELINE → bambu doesn't support it, comment out
        if "PIPELINE" in upper:
            translated.append(f"{indent}// [bambu] {stripped}")
            continue

        # INTERFACE pragma translation
        if "INTERFACE" in upper:
            parts = stripped.split()
            try:
                iface_idx = next(i for i, p in enumerate(parts) if p.upper() == "INTERFACE")
            except StopIteration:
                translated.append(line)
                continue

            # Parse remaining tokens
            mode = None
            new_parts = parts[:iface_idx + 1]  # "#pragma HLS INTERFACE"
            rest = parts[iface_idx + 1:]

            i = 0
            filtered_rest = []
            while i < len(rest):
                token = rest[i]
                if "=" in token:
                    key, val = token.split("=", 1)
                    key_lower = key.lower()
                    if key_lower == "mode":
                        mode = IFACE_MAP.get(val.lower(), val.lower())
                    elif key_lower == "port":
                        # Skip port=return (bambu infers it)
                        if val != "return":
                            filtered_rest.append(f"port={val}")
                    elif key_lower in ("offset", "depth", "bundle", "name"):
                        pass  # Drop Vitis-specific attributes
                    else:
                        filtered_rest.append(token)
                else:
                    # Bare token after INTERFACE = the mode
                    mapped = IFACE_MAP.get(token.lower())
                    if mapped:
                        mode = mapped
                    else:
                        filtered_rest.append(token)
                i += 1

            # Skip port=return lines entirely (bambu auto-infers control interface)
            port_tokens = [t for t in filtered_rest if t.startswith("port=")]
            if not port_tokens and mode in ("ap_hs", "ap_none"):
                # This is a control interface pragma (port=return) — skip entirely
                translated.append(f"{indent}// [bambu] {stripped}")
                continue

            if mode:
                new_parts.append(f"mode={mode}")
            new_parts.extend(filtered_rest)
            translated.append(f"{indent}{' '.join(new_parts)}")
            continue

        # UNROLL, INLINE, DATAFLOW — pass through as-is (bambu supports these)
        translated.append(line)

    wrapper_path = os.path.join(output_dir, "bambu_wrapper.cpp")
    with open(wrapper_path, "w") as f:
        f.write("\n".join(translated))
    return wrapper_path


