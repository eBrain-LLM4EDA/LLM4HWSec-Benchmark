@dataclass
class BambuConfig:
    """Configuration for bambu invocation."""
    bambu_bin: str = "bambu"           # Path to bambu binary / AppImage
    simulator: str = "VERILATOR"       # VERILATOR, ICARUS, MODELSIM
    clock_period: float = 10.0         # Target clock period (ns)
    device: str = "xc7z020-1clg484-VVD"  # Default: Zynq-7020
    timeout: int = 300                 # Seconds per synthesis run
    extra_args: List[str] = field(default_factory=list)


