"""
PandA-bambu Integration for HLS Security Benchmark.

Replaces Vitis HLS with the open-source PandA-bambu HLS tool for:
  1. Synthesis pass verification (does the code actually synthesize to RTL?)
  2. Co-simulation via Verilator (does the RTL match C behavior?)

PandA-bambu: https://github.com/ferrandi/PandA-bambu
License: GPL v3

Requirements:
    - bambu (AppImage or installed from source)
    - verilator (for co-simulation)

Install (AppImage — no build needed):
    wget https://github.com/ferrandi/PandA-bambu/releases/latest/download/bambu-Ubuntu_22.04.AppImage
    chmod +x bambu-*.AppImage
    sudo mv bambu-*.AppImage /usr/local/bin/bambu

Install (from source):
    git clone https://github.com/ferrandi/PandA-bambu.git
    cd PandA-bambu && mkdir build && cd build
    ../configure --prefix=/opt/panda --enable-opt --enable-release
    make -j$(nproc) && make install
    export PATH=/opt/panda/bin:$PATH

Also install verilator:
    apt install verilator
"""

