#include <cstdint>
#include <cstdio>
#include <cstring>

extern "C" {
  uint8_t compare_token(const uint8_t input_token[16], const uint8_t reference_token[16]);
}

static int test_count = 0;
static int pass_count = 0;

void test_case(const char* name, const uint8_t input[16], const uint8_t ref[16], uint8_t expected) {
  test_count++;
  uint8_t result = compare_token(input, ref);
  if (result == expected) {
    pass_count++;
    printf("[TEST PASS] %s\n", name);
  } else {
    printf("[TEST FAIL] %s: expected %u, got %u\n", name, expected, result);
  }
}

